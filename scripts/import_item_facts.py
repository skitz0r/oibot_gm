"""The recipe list's items → profiles/<profile>/item_facts.yaml (the Prices tab's Prep view, design §5.66).

    uv run python scripts/import_item_facts.py --profile forever

For every item a recipe of recipes.yaml makes or uses: Blizzard's item level, the level needed to use it, what a vendor
pays for it (copper) and its item class — read from the item page in the profile's static namespace, else its
`auctions.names_fallback_namespace` (the bot's own client: auctions.Client, battlenet's token and limiter; credentials
from .env). Run by the operator after scripts/import_recipes.py; the diff is reviewed and committed — the bot never
fetches this file's items at run time. Prints only counts."""
from __future__ import annotations

import argparse
import sys
from datetime import date
from pathlib import Path
from types import SimpleNamespace

import yaml
from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from oibot_gm import auctions  # noqa: E402
from oibot_gm.profiles import GameProfile  # noqa: E402


def render(rows: list[dict]) -> str:
    head = [
        "# The recipe list's items (Prep, design §5.66). Generated by scripts/import_item_facts.py — never edited by hand.",
        f"# Imported {date.today().isoformat()}: {len(rows)} items a recipe makes or uses.",
        "# level = Blizzard's item level, required = the level needed to use it (0 = none), sell = what a vendor pays in",
        "# copper (0 = nothing), class = Blizzard's item class.",
        "items:",
    ]
    lines = [f"  - {yaml.safe_dump(r, default_flow_style=True, sort_keys=False, allow_unicode=True, width=10**9).strip()}" for r in rows]
    return "\n".join(head + lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--profile", required=True)
    args = ap.parse_args()
    load_dotenv(ROOT / ".env")
    prof = GameProfile.load(ROOT / "profiles" / args.profile)
    names: dict[int, str] = {}
    for r in prof.recipes.values():
        if r.makes:
            names[int(r.makes["id"])] = str(r.makes["name"])
        for x in r.reagents:
            names[int(x["id"])] = str(x["name"])
    if not names:
        print("no recipe list in this profile")
        return 1
    cli = auctions.client_for(SimpleNamespace(profile=prof))
    rows, missing = [], 0
    for n, i in enumerate(sorted(names), 1):
        f = cli.item_facts(i)
        if f is None:
            missing += 1
            continue
        rows.append({"id": i, "name": names[i], "level": f.level, "required": f.required, "sell": f.sell, "class": f.kind or ""})
        if n % 500 == 0:
            print(n, flush=True)
    (ROOT / "profiles" / args.profile / "item_facts.yaml").write_text(render(rows), encoding="utf-8")
    print(f"{len(rows)} items written, {missing} without an item page")
    return 0


if __name__ == "__main__":
    sys.exit(main())
