"""The game's recipe list → profiles/<profile>/recipes.yaml (armory link, spec §4.1).

    uv run python scripts/import_recipes.py --profile forever [--region us]

Walks the static namespace (the profile's integrations.yaml `armory.static_namespace`, else `blizzard_namespace`):
profession index → profession → skill tier → recipe, for the professions that carry a `blizzard_id` in
professions.yaml. Run by the operator after a game build; the diff is reviewed and committed — the bot never fetches the
list at run time. Responses are cached in out/blizzard_cache (a re-run is cheap; delete it for a new build), requests are
paced at ≤ 10 a second, and the credentials come from .env. Prints only counts."""
from __future__ import annotations

import argparse
import sys
from collections import Counter
from datetime import date
from pathlib import Path

import yaml
from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from oibot_gm.importers.blizzard import Blizzard, recipe_rows  # noqa: E402
from oibot_gm.profiles import GameProfile  # noqa: E402


def render(rows: list[dict], build: str, counts: dict[str, int], names: dict[str, str]) -> str:
    """The file: a header (build, date, counts per profession) and one flow-style line per recipe (a diff per recipe)."""
    head = [
        "# The game's recipe list (armory link, spec §4.1). Generated by scripts/import_recipes.py — never edited by hand.",
        f"# Build {build or 'unknown'}, imported {date.today().isoformat()}: {len(rows)} recipes.",
        "# " + ", ".join(f"{names.get(p, p)} {n}" for p, n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))),
        "# makes: {id, name, quantity} of the item (+ quantity_max when the count varies), or null (an enchant); reagents: [{id, name, quantity}].",
        "recipes:",
    ]
    lines = [f"  - {yaml.safe_dump(r, default_flow_style=True, sort_keys=False, allow_unicode=True, width=10**9).strip()}" for r in rows]
    return "\n".join(head + lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--profile", default="forever")
    ap.add_argument("--region", default=None, help="default: the profile's armory region")
    a = ap.parse_args()
    load_dotenv(ROOT / ".env")
    root = ROOT / "profiles" / a.profile
    prof = GameProfile.load(root)
    ids = {d.blizzard_id: d.id for d in prof.professions.values() if d.blizzard_id is not None}
    if not ids:
        print(f"{a.profile}: no profession carries a blizzard_id in professions.yaml; nothing to import")
        return 1
    region = a.region or (prof.armory or {}).get("region") or "us"
    integ = yaml.safe_load((root / "integrations.yaml").read_text()) or {}
    ns = ((prof.armory or {}).get("static_namespace") or integ.get("blizzard_namespace") or "").format(region=region)
    bz = Blizzard(region=region, namespace=ns, cache_dir=ROOT / "out" / "blizzard_cache")
    rows, build = recipe_rows(bz, ids)
    counts = Counter(r["profession"] for r in rows)
    names = {d.id: d.name for d in prof.professions.values()}
    (root / "recipes.yaml").write_text(render(rows, build, dict(counts), names))
    print(f"build {build or 'unknown'}: {len(rows)} recipes, {len(counts)} professions")
    for pid, n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])):
        print(f"  {names.get(pid, pid)} {n}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
